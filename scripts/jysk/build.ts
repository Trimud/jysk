// Turns scripts/jysk/facts.json into the rows we draw: npm run jysk:build
// Out: src/data/jysk-rows.ts (one row per line, see encodeRow in src/lib/ikea.ts).
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { encodeRow, type IkeaRow } from "@/lib/ikea";
import type { Facts } from "./fetch";

const DIR = import.meta.dirname;
const OUT = path.join(DIR, "../../src/data/jysk-rows.ts");

const num = (s?: string) => (s ? Number(s.match(/\d+/)?.[0]) : undefined);

/** "Width 81 cm, Height 101 cm, Depth 48 cm" as [w, h, d] in cm. */
function size(s: string): [number, number, number] | null {
  const get = (k: string) => Number(s.match(new RegExp(`${k} (\\d+(?:\\.\\d+)?) cm`))?.[1]);
  const v: [number, number, number] = [get("Width"), get("Height"), get("Depth")];
  return v.every((n) => n > 0) ? v : null;
}

// ponytail: rules for the pilot's categories only; Phase 3 extends them to the full furniture range
function classify(f: Facts): { row: IkeaRow } | { skip: string } {
  const dims = size(f.specs["Size assembled"] ?? "");
  if (!dims) return { skip: `no assembled size: ${f.specs["Size assembled"]}` };
  const [w, h, d] = dims;
  const name = f.family;
  const variant = f.name.replace(new RegExp(`\\s*${f.family}\\s*`, "i"), " ").trim().replace(/^./, (c) => c.toUpperCase());
  const base = { name, variant, w, h, d, keywords: [f.sku], slug: f.slug };
  const drawers = num(f.specs["Number of drawers"]);
  switch (f.category) {
    case "Chest of Drawers":
      if (!drawers) return { skip: "chest without a drawer count" };
      return { row: { ...base, kind: "chest", x: { rows: drawers } } };
    case "Wardrobes": {
      const doors = num(f.specs["Number of doors"]);
      if (doors !== 1 && doors !== 2) return { skip: `wardrobe with ${doors ?? "no"} hinged doors` };
      // with drawers it is the "mixed" kind (a wardrobe with drawers), else a plain wardrobe
      return { row: { ...base, kind: drawers ? "mixed" : "wardrobe", x: { doors, shelves: num(f.specs["Number of shelves"]) ?? 1, rail: !!num(f.specs["Number of hanging rails"]), rows: drawers } } };
    }
    default:
      return { skip: `category not classified yet: ${f.category}` };
  }
}

const facts: Facts[] = JSON.parse(readFileSync(path.join(DIR, "facts.json"), "utf8"));
const rows: string[] = [];
for (const f of facts) {
  const c = classify(f);
  if ("skip" in c) console.log(`skip ${f.sku} ${f.name}: ${c.skip}`);
  else rows.push(encodeRow(c.row));
}
writeFileSync(
  OUT,
  `// Generated by scripts/jysk/build.ts from JYSK UK product pages. Do not edit by hand.\n// Rows we can draw, one per line: name|kind|variant|w|h|d|params|keywords|slug\nexport const JYSK_ROWS = \`${rows.join("\n")}\`;\n`,
);
console.log(`${rows.length} of ${facts.length} products -> src/data/jysk-rows.ts`);
