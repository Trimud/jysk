// Lists every JYSK UK furniture product page from the sitemap: npm run jysk:discover
// Out: scripts/jysk/range.txt (one URL per line), read by npm run jysk:fetch after pilot.txt.
// Only furniture someone builds: textiles, decoration and the like are left out here, and the fetcher drops anything sold assembled.
import { writeFileSync } from "node:fs";
import path from "node:path";

const DIR = import.meta.dirname;
const UA = "AssembleHelp/0.1 (+https://assemble.help)";

/** Category paths whose leaves are furniture. Dining sets are left out: each piece has its own page. */
const FURNITURE = new RegExp(
  "^https://jysk\\.co\\.uk/(" +
    [
      "bedroom/(beds|bedside-tables)/",
      "dining-room/(bar-stools|cabinets|console|dining-chairs|dining-tables|folding|sideboards)[^/]*/",
      "garden/(garden-furniture|garden-storage)[^/]*/",
      "hall/",
      "homeware/kids-furniture/",
      "living-room/(armchairs|coffee|modular|pouffes|sofa|tv-units)[^/]*/",
      "office/(desks|gaming|office-chairs|standing)[^/]*/",
      "storage/(bookshelves|chest|clothes-rails|misc|shelves|shoe|wardrobes)[^/]*/",
      "bathroom/bathroom-accessories/[^/]*/[^/]*shelving",
    ].join("|") +
    ")",
);

const xml = await (await fetch("https://jysk.co.uk/sitemap.xml", { headers: { "User-Agent": UA } })).text();
const all = [...new Set([...xml.matchAll(/<loc>([^<]+)<\/loc>/g)].map((m) => m[1].replace("https://jysk.uk/", "https://jysk.co.uk/")))];
// a product page is a leaf: no other address sits under it (category pages do)
const leaves = all.filter((u) => !all.some((v) => v.startsWith(u + "/")));
const range = leaves.filter((u) => FURNITURE.test(u)).sort();
writeFileSync(path.join(DIR, "range.txt"), `# Generated by scripts/jysk/discover.ts from jysk.co.uk/sitemap.xml. Do not edit by hand.\n${range.join("\n")}\n`);
console.log(`${range.length} furniture pages of ${leaves.length} -> scripts/jysk/range.txt`);
